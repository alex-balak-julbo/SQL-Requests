SELECT
    BPCUSTOMER.BPCSTA_0,
    BPARTNER.BPRNUM_0,
    BPCUSTOMER.BPCGRU_0,
    BPCUSTOMER.BCGCOD_0,
    BPCUSTOMER.BUS_0,
    BPCUSTOMER.REP_0,
    BPADDRESS.CRY_0,
    BPADDRESS.CRYNAM_0,
    BPCUSTOMER.BPCNAM_0,
    BPADDRESS.BPAADD_0,
    BPADDRESS.BPAADDLIG_0,
    BPADDRESS.BPAADDLIG_1,
    BPADDRESS.BPAADDLIG_2,
    BPADDRESS.POSCOD_0,
    BPADDRESS.CTY_0,
    BPADDRESS.WEB_0,
    BPARTNER.CUR_0,
    BPCUSTOMER.IME_0,
    BPCUSTOMER.TSCCOD_0,
    BPCUSTOMER.TSCCOD_1,
    BPCUSTOMER.TSCCOD_2,
    BPCUSTOMER.TSCCOD_3,
    BPCUSTOMER.TSCCOD_4,
    BPCUSTOMER.ACCCOD_0,
    BPCUSTOMER.VACBPR_0,
    BPCUSTOMER.PTE_0,
    BPCUSTOMER.FUPTYP_0,
    BPCUSTOMER.YEDITYPENV_0,
    BPCUSTOMER.YEDIMAIL_0,
    BPDLVCUST.MDL_0,
    BPDLVCUST.BPTNUM_0,
    BPARTNER.ZNBBL_0,
    BPARTNER.ZNBBC_0,
    BPARTNER.ZNBBLCH_0,
    BPARTNER.ZNBBLINT_0,
    BPARTNER.ZNBETQPP_0,
    BPARTNER.ZPROFLOG_0,
    BPARTNER.CRN_0,
    BPARTNER.EECNUM_0
FROM YCLIGRP
INNER JOIN BPARTNER ON BPARTNER.BPRNUM_0 = YCLIGRP.YBPCNUM_0
INNER JOIN BPCUSTOMER ON BPCUSTOMER.BPCNUM_0 = YCLIGRP.YBPCNUM_0
LEFT JOIN BPADDRESS ON BPADDRESS.BPANUM_0 = BPARTNER.BPRNUM_0 AND BPADDRESS.BPAADD_0 = BPARTNER.BPAADD_0
LEFT JOIN BPDLVCUST ON BPDLVCUST.BPCNUM_0 = BPARTNER.BPRNUM_0 AND BPDLVCUST.BPAADD_0 = BPARTNER.BPAADD_0
WHERE (YCLIGRP.YGROUPE_0 = %1% OR RTRIM(%1%) IS NULL OR RTRIM(%1%) = '')
  AND CAST(GETDATE() AS DATE) BETWEEN YCLIGRP.DATDEB_0 AND YCLIGRP.DATFIN_0