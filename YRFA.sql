select sv.BPCORD_0, bo.BPCNAM_0, sv.BPRPAY_0, bp.BPCNAM_0, sv.BPCGRU_0, sv.YGRPNAM_0, sv.YNUMADH_0, se.CUR_0, se.RATMLT_0, sd.ITMREF_0, sd.ITMDES_0, TEX2.TEXTE_0, se.SNS_0, (sd.GROPRI_0*se.SNS_0*sd.QTY_0), (sd.AMTNOTLIN_0*se.SNS_0), (sd.QTY_0*sd.NETPRIATI_0*se.SNS_0), it.X6RFA_0, se.NUM_0, sv.INVDAT_0, sv.YNATURE_0, TEX1.TEXTE_0, TEX3.TEXTE_0, BPDCTY_0


FROM SINVOICE se 
JOIN SINVOICEV sv ON se.NUM_0=sv.NUM_0 
JOIN SINVOICED sd ON se.NUM_0=sd.NUM_0

left outer join ATABDIV DIV2 on DIV2.CODE_0 = sd.TSICOD_1
and DIV2.NUMTAB_0=21
Left outer Join ATEXTRA TEX2 on TEX2.CODFIC_0='ATABDIV' 
and TEX2.LANGUE_0='FRA'
and TEX2.ZONE_0='LNGDES'
and TEX2.IDENT1_0=21
and TEX2.IDENT2_0=DIV2.CODE_0



JOIN BPCUSTOMER bp ON sv.BPRPAY_0=bp.BPCNUM_0
JOIN BPCUSTOMER bo ON sv.BPCORD_0=bo.BPCNUM_0
JOIN ITMSALES it ON sd.ITMREF_0=it.ITMREF_0

left outer join ATABDIV DIV1 on DIV1.CODE_0 = bo.TSCCOD_3
AND DIV1.NUMTAB_0 = 33
Left outer Join ATEXTRA TEX1 on TEX1.CODFIC_0='ATABDIV' 
and TEX1.LANGUE_0='FRA'
and TEX1.ZONE_0='LNGDES'
and TEX1.IDENT1_0=33
and TEX1.IDENT2_0=DIV1.CODE_0

left outer join ATABDIV DIV3 on DIV3.CODE_0 = bo.TSCCOD_1
AND DIV3.NUMTAB_0 = 31
Left outer Join ATEXTRA TEX3 on TEX3.CODFIC_0='ATABDIV' 
and TEX3.LANGUE_0='FRA'
and TEX3.ZONE_0='LNGDES'
and TEX3.IDENT1_0=31
and TEX3.IDENT2_0=DIV3.CODE_0



where (se.INVTYP_0=1 or se.INVTYP_0=2 )
and sv.INVDAT_0 between %1% and %2%
and sv.BPCORD_0 between %3% and %4%
and sv.BPRPAY_0 between %5% and %6%
and sv.BPCGRU_0 between %7% and %8%
and it.X6RFA_0 between %9% and %10%
and sv.YNATURE_0 between %11% and %12%


